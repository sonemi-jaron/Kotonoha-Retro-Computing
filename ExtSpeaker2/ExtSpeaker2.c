/* 16進数文字を数値に変換 */
unsigned char hex2val(char c) {
    if (c >= '0' && c <= '9') return c - '0';
    if (c >= 'A' && c <= 'F') return c - 'A' + 10;
    if (c >= 'a' && c <= 'f') return c - 'a' + 10;
    return 0;
}

/* 2文字の16進数文字列を1バイトに変換 */
unsigned char h2b(const char *s) {
    return (hex2val(s[0]) << 4) | hex2val(s[1]);
}

