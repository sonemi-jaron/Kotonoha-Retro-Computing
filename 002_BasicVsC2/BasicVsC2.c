void gprintEx(int x,int y,int l,char *data[]){
 int i=0,j,len,w;
 char buff[255];
 while(data[i] != NULL) {
  if(y>=0 && y<48){
   strcpy(buff,"");
   for(j=0;j<l;j++) strcat(buff,data[i+j]);
   len=strlen(buff);
   //gcursor(x,y); gprint(buff);
   poke(0x100, x);
   poke(0x101, y/8);
   w=len/2;  poke(0x102, w);
   call(0x110, (void*)buff);
  }
  y+=8;
  i+=l;
 }
}
